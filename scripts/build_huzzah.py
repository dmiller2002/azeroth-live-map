#!/usr/bin/env python3
"""Pack generated artwork into matching WoW and browser transport assets.

This only aligns, palette-packs and exports the generated sprite sheet; creative
changes/animation frames come from the image-generation tool, not this script.
Requires Pillow for asset preparation, not for running the addon/companion.
"""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
source = Image.open(ROOT / 'assets/huzzah-idle-source.png').convert('RGBA')
width, height = 64, 64
frames = []
for i in range(8):
    cell = source.crop((i % 4 * source.width // 4, i // 4 * source.height // 2,
                        (i % 4 + 1) * source.width // 4, (i // 4 + 1) * source.height // 2))
    sprite = cell.crop(cell.getchannel('A').point(lambda alpha: 255 if alpha >= 128 else 0).getbbox())
    scale = min(62 / sprite.width, 60 / sprite.height)
    sprite = sprite.resize((round(sprite.width * scale), round(sprite.height * scale)), Image.Resampling.NEAREST)
    canvas = Image.new('RGBA', (width, height))
    canvas.alpha_composite(sprite, ((width - sprite.width) // 2, 62 - sprite.height))
    frames.append(canvas)

# Pick carriers only where every animation frame is opaque. The silhouette and
# transparent background cannot change a transmitted bit or depend on game pixels.
common = [y * width + x for y in range(height) for x in range(width)
          if all(frame.getpixel((x, y))[3] >= 240 for frame in frames)]
assert len(common) >= 960, 'Not enough opaque pixels for five checksummed packets'
# Spread the data through the body, leaving some ordinary artwork between bits.
positions = [common[i * len(common) // 960] for i in range(960)]
palette, lookup, encoded = [[0, 0, 0, 0]], {(0, 0, 0, 0): 0}, []
atlas = Image.new('RGBA', (512, 64))
for i, frame in enumerate(frames):
    indices = []
    for y in range(height):
        for x in range(width):
            r, g, b, alpha = frame.getpixel((x, y))
            # Keep headroom for a +/-24 red-channel carrier, in every shade.
            # Keep the generated palette, reserving transport signal headroom.
            color = (max(32,min(223,r)), round(g / 8) * 8, round(b / 8) * 8, 255) if alpha >= 128 else (0, 0, 0, 0)
            color = tuple(min(255, value) for value in color)
            if color not in lookup:
                lookup[color] = len(palette); palette.append(list(color))
            indices.append(lookup[color]);atlas.putpixel((i * 64 + x, y), color)
    encoded.append(indices)
asset = dict(width=width, height=height, footerRows=4, delta=24, positions=positions,
             palette=palette, frames=encoded, durations=[12, 3, 2, 1, 3, 2, 3, 12])
(ROOT / 'dist/elephant-art.json').write_text(json.dumps(asset, separators=(',', ':')) + '\n')
atlas.save(ROOT / 'addon/AzerothLiveMap/Elephant.tga')
atlas.save(ROOT / 'dist/elephant-atlas.png')
# Numeric tables avoid version-specific binary/bitwise APIs in WoW's Lua 5.1.
def lua(value):
    if isinstance(value, list): return '{' + ','.join(lua(item) for item in value) + '}'
    return str(value)
lines = ['-- Generated by scripts/build_huzzah.py; source: assets/huzzah-idle-source.png',
         'local _, ns = ...', 'ns.Elephant = {']
for key in ('width', 'height', 'footerRows', 'delta', 'positions', 'palette', 'frames', 'durations'):
    lines.append('  ' + key + ' = ' + lua(asset[key]) + ',')
lines.append('}\n')
(ROOT / 'addon/AzerothLiveMap/Elephant.lua').write_text('\n'.join(lines))
print(f'Packed 8 HUZZAH frames, {len(palette)} colors and {len(positions)} carrier pixels.')
